#include "am_cpu_test.h"

#define N 31

static int a[N];
static int ans[] = {
    1, 30, 435, 4060, 27405, 142506, 593775, 2035800, 5852925, 14307150,
    30045015, 54627300, 86493225, 119759850, 145422675, 155117520, 145422675, 119759850, 86493225, 54627300,
    30045015, 14307150, 5852925, 2035800, 593775, 142506, 27405, 4060, 435, 30, 1};

int main(void) {
  a[0] = 1;
  a[1] = 1;

  for (int i = 2; i < N; i++) {
    int t0 = 1;
    for (int j = 1; j < i; j++) {
      int t1 = a[j];
      a[j] = t0 + t1;
      t0 = t1;
    }
    a[i] = 1;
  }

  for (int j = 0; j < N; j++) {
    check(a[j] == ans[j]);
  }

  return 0;
}
