#include "am_cpu_test.h"

static int max2(int x, int y) {
  return x > y ? x : y;
}

static int test_data[] = {0, 1, 2, 0x7fffffff, 0x80000000, 0x80000001, 0xfffffffe, 0xffffffff};
static int ans[] = {
    0, 0x1, 0x2, 0x7fffffff, 0, 0, 0, 0,
    0x1, 0x1, 0x2, 0x7fffffff, 0x1, 0x1, 0x1, 0x1,
    0x2, 0x2, 0x2, 0x7fffffff, 0x2, 0x2, 0x2, 0x2,
    0x7fffffff, 0x7fffffff, 0x7fffffff, 0x7fffffff, 0x7fffffff, 0x7fffffff, 0x7fffffff, 0x7fffffff,
    0, 0x1, 0x2, 0x7fffffff, 0x80000000, 0x80000001, 0xfffffffe, 0xffffffff,
    0, 0x1, 0x2, 0x7fffffff, 0x80000001, 0x80000001, 0xfffffffe, 0xffffffff,
    0, 0x1, 0x2, 0x7fffffff, 0xfffffffe, 0xfffffffe, 0xfffffffe, 0xffffffff,
    0, 0x1, 0x2, 0x7fffffff, 0xffffffff, 0xffffffff, 0xffffffff, 0xffffffff};

int main(void) {
  int ans_idx = 0;

  for (int i = 0; i < LENGTH(test_data); i++) {
    for (int j = 0; j < LENGTH(test_data); j++) {
      check(max2(test_data[i], test_data[j]) == ans[ans_idx++]);
    }
  }

  return 0;
}
