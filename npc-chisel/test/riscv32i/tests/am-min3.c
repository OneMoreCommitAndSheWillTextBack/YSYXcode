#include "am_cpu_test.h"

static int min3(int x, int y, int z) {
  int m = x < y ? x : y;
  return z < m ? z : m;
}

static int test_data[] = {0, 0x7fffffff, 0x80000000, 0xffffffff};
static int ans[] = {
    0, 0, -2147483648, -1, 0, 0, -2147483648, -1,
    -2147483648, -2147483648, -2147483648, -2147483648, -1, -1, -2147483648, -1,
    0, 0, -2147483648, -1, 0, 2147483647, -2147483648, -1,
    -2147483648, -2147483648, -2147483648, -2147483648, -1, -1, -2147483648, -1,
    -2147483648, -2147483648, -2147483648, -2147483648, -2147483648, -2147483648, -2147483648, -2147483648,
    -2147483648, -2147483648, -2147483648, -2147483648, -2147483648, -2147483648, -2147483648, -2147483648,
    -1, -1, -2147483648, -1, -1, -1, -2147483648, -1,
    -2147483648, -2147483648, -2147483648, -2147483648, -1, -1, -2147483648, -1};

int main(void) {
  int ans_idx = 0;

  for (int i = 0; i < LENGTH(test_data); i++) {
    for (int j = 0; j < LENGTH(test_data); j++) {
      for (int k = 0; k < LENGTH(test_data); k++) {
        check(min3(test_data[i], test_data[j], test_data[k]) == ans[ans_idx++]);
      }
    }
  }

  return 0;
}
